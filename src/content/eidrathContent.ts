/**
 * Validates all authored content references, duplicate IDs, prerequisite cycles,
 * recipes, dialogues, and attack bindings at startup and in unit tests (Section 16).
 */
export function validateEidrathContent(): { valid: boolean; errors: string[] } {
  const errors: string[] = [];

  // 1. Check duplicate IDs in lists
  const checkUnique = (list: Array<{ id: string }>, label: string) => {
    const seen = new Set<string>();
    for (const entry of list) {
      if (seen.has(entry.id)) errors.push(`Duplicate ${label} ID: ${entry.id}`);
      seen.add(entry.id);
    }
  };
  checkUnique(FROSTHEIM_LANDMARKS, 'landmark');
  checkUnique(SKILL_NODES, 'skill');
  checkUnique(QUESTS, 'quest');
  checkUnique(CRAFTING_RECIPES, 'recipe');
  checkUnique(LORE_ENTRIES, 'lore');

  // 2. Skill tree prerequisite references & cycle check
  const skillMap = new Map(SKILL_NODES.map((n) => [n.id, n]));
  for (const node of SKILL_NODES) {
    for (const req of node.prerequisites) {
      if (!skillMap.has(req)) errors.push(`Skill ${node.id} references missing prereq ${req}`);
    }
    const visiting = new Set<string>();
    const hasCycle = (id: string): boolean => {
      if (visiting.has(id)) return true;
      visiting.add(id);
      const cur = skillMap.get(id);
      if (!cur) return false;
      for (const p of cur.prerequisites) {
        if (hasCycle(p)) return true;
      }
      visiting.delete(id);
      return false;
    };
    if (hasCycle(node.id)) errors.push(`Skill prerequisite cycle detected at ${node.id}`);
  }

  // 3. Quests references
  const questIds = new Set(QUESTS.map((q) => q.id));
  for (const q of QUESTS) {
    for (const req of q.prerequisites) {
      if (!questIds.has(req)) errors.push(`Quest ${q.id} missing prerequisite quest ${req}`);
    }
    for (const rItem of q.rewards.items ?? []) {
      if (!ITEMS[rItem.itemId]) errors.push(`Quest ${q.id} rewards unknown item ${rItem.itemId}`);
    }
  }

  // 4. Crafting recipes
  for (const r of CRAFTING_RECIPES) {
    for (const ing of r.ingredients) {
      if (!ITEMS[ing.itemId]) errors.push(`Recipe ${r.id} missing ingredient item ${ing.itemId}`);
    }
    if (r.outputItemId && !ITEMS[r.outputItemId]) {
      errors.push(`Recipe ${r.id} missing output item ${r.outputItemId}`);
    }
    if (r.upgradeTargetItemId && !ITEMS[r.upgradeTargetItemId]) {
      errors.push(`Recipe ${r.id} missing upgrade target item ${r.upgradeTargetItemId}`);
    }
  }

  // 5. Dialogue nextNodeId & item/quest links
  for (const node of Object.values(DIALOGUES)) {
    for (const ch of node.choices) {
      if (ch.nextNodeId && !DIALOGUES[ch.nextNodeId]) {
        errors.push(`Dialogue ${node.id}/${ch.id} references unknown node ${ch.nextNodeId}`);
      }
      if (ch.effects?.startQuestId && !questIds.has(ch.effects.startQuestId)) {
        errors.push(`Dialogue ${node.id}/${ch.id} starts unknown quest ${ch.effects.startQuestId}`);
      }
      if (ch.effects?.grantItem && !ITEMS[ch.effects.grantItem.itemId]) {
        errors.push(`Dialogue ${node.id}/${ch.id} grants unknown item ${ch.effects.grantItem.itemId}`);
      }
    }
  }

  // 6. Enemy attack bindings & loot items
  for (const enm of Object.values(ENEMY_ARCHETYPES)) {
    for (const atkId of enm.attacks) {
      if (!ATTACKS[atkId]) errors.push(`Enemy ${enm.id} references unknown attack ${atkId}`);
    }
    for (const drop of enm.lootTable) {
      if (!ITEMS[drop.itemId]) errors.push(`Enemy ${enm.id} drops unknown item ${drop.itemId}`);
    }
  }

  // 7. Boss phase attacks
  for (const bp of MOUNTAIN_WARDEN_PHASES) {
    for (const atkId of bp.attackIds) {
      if (!ATTACKS[atkId]) errors.push(`Boss phase ${bp.phase} references unknown attack ${atkId}`);
    }
  }

  return { valid: errors.length === 0, errors };
}
